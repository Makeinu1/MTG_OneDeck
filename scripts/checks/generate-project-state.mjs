#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { pathToFileURL } from 'node:url';

export const repositoryRoot = resolve(import.meta.dirname, '../..');
const generatedPath = resolve(repositoryRoot, 'docs/generated/project-state.md');

function readJson(path) { return JSON.parse(readFileSync(path, 'utf8')); }
function mdCode(value) { return `\`${String(value).replaceAll('`', '\\`')}\``; }
function refs(values) {
  if (!Array.isArray(values) || values.length === 0) return '—';
  return values
    .map((entry) => mdCode(entry.locator ? `${entry.path} :: ${entry.locator}` : entry.path))
    .join('<br>');
}

export function loadProjectState(root = repositoryRoot) {
  const index = readJson(resolve(root, 'docs/project-state/index.json'));
  const capabilities = index.capabilities.map((entry) => readJson(resolve(root, entry.path)));
  return { index, capabilities };
}

export function renderProjectState({ index, capabilities }) {
  const conflicts = capabilities.filter((item) => item.semanticVerdict === 'CONFLICT');
  const gaps = capabilities.filter((item) => item.semanticVerdict === 'GAP');
  const lifecycle = capabilities.filter((item) => item.lifecycle !== 'ACTIVE');
  const pendingDecisions = Array.isArray(index.pendingDecisions) ? index.pendingDecisions : [];
  const lines = [
    '<!-- GENERATED by scripts/checks/generate-project-state.mjs. DO NOT EDIT. -->',
    '# Current Project State', '',
    `Canonical source: ${mdCode('docs/project-state/index.json')} + indexed capability files.`,
    `Audited baseline: ${mdCode(index.baseline.commit)} (${index.baseline.branch}, ${index.baseline.auditedDate}).`,
    'Authority note: this generated view is committed project NOW only on `main`; on any non-main branch it is a candidate Project State until merged.', '',
    '## Restart entry', '',
    `- Product goal: ${mdCode(index.authorities.productGoal)}`,
    `- Constitution: ${mdCode(index.authorities.constitution)}`,
    `- Active contract registry: ${mdCode(index.authorities.contractRegistry)}`,
    `- Traceability: ${mdCode(index.authorities.traceabilityRegistry)}`,
    `- Acceptance registry: ${mdCode(index.authorities.acceptanceRegistry)}`,
    `- Production implementation roots: ${index.authorities.productionImplementation.map(mdCode).join(', ')}`,
    `- Production routing map: ${mdCode(index.roles.productionImplementationMap)}`,
    `- NOW authority: ${mdCode(index.roles.nowAuthority)}`,
    `- Roadmap / provenance / history: ${mdCode(index.roles.roadmapHistory)}`,
    `- Roadmap authority policy: ${mdCode(index.roles.roadmapHistoryPolicy)}`, '',
    'Historical `activeProgram`, `nextGate`, planned-sequence or "single source" wording inside CR-grounding material does not override Project State NOW.', '',
    'Issues, pull requests and CI are evidence/work surfaces. They are not canonical NOW and do not independently establish semantic correctness.', '',
    '## Reconstruction program', '',
    `- Completed: ${index.program.completedMilestones.map(mdCode).join(', ') || '—'}`,
    `- Active: ${mdCode(index.program.activeMilestone)}`,
    `- Next gate: ${mdCode(index.program.nextGate)}`,
    `- Next work: ${index.program.nextWork}`, '',
    '## Coverage claim', '',
    `- Mode: ${mdCode(index.coverage.mode)}`,
    `- Scope: ${index.coverage.scope}`,
    `- Completeness sources: ${index.coverage.completenessSources.map(mdCode).join(', ')}`,
    '- Known limitations:',
    ...index.coverage.knownLimitations.map((item) => `  - ${item}`), '',
    '## Capability state', '',
    '| ID | Capability | Requirement | Semantic | Delivery | Lifecycle |',
    '| --- | --- | --- | --- | --- | --- |',
    ...capabilities.map((item) => `| ${item.id} | ${item.title} | ${item.requirementLevel} | ${item.semanticVerdict} | ${item.deliveryState} | ${item.lifecycle} |`), '',
    '## Explicit conflicts', '',
    ...(conflicts.length ? conflicts.flatMap((item) => [`### ${item.id} — ${item.title}`, '', item.rationale, '', `Authority: ${refs(item.authorityRefs)}`, '', `Implementation: ${refs(item.implementationRefs)}`, '', `Next: ${item.nextAction}`, '']) : ['None recorded at this baseline.', '']),
    '## Implementation gaps', '',
    ...(gaps.length ? gaps.flatMap((item) => [`### ${item.id} — ${item.title}`, '', item.rationale, '', `Next: ${item.nextAction}`, '']) : ['None recorded at this baseline.', '']),
    '## Lifecycle warnings', '',
    ...(lifecycle.length ? lifecycle.map((item) => `- ${item.id}: ${item.lifecycle} — ${item.title}`) : ['- No DEPRECATED or RETIRED capability entries are recorded at this baseline.']), '',
    '## Pending decisions', '',
    ...(pendingDecisions.length
      ? pendingDecisions.flatMap((decision) => [
          `### ${decision.id} — ${decision.status}`,
          '',
          decision.summary,
          '',
          `Traceability: ${decision.traceabilityRefs.map(mdCode).join(', ') || '—'}`,
          `Acceptance: ${decision.acceptanceRefs.map(mdCode).join(', ') || '—'}`,
          ...(decision.ownerDecisionRef ? [`Owner decision: ${mdCode(decision.ownerDecisionRef)}`] : []),
          '',
          `Next: ${decision.nextAction}`,
          '',
        ])
      : ['None.', '']),
    '## Owner decisions', '',
    ...index.ownerDecisions.map((decision) => decision.status === 'RESOLVED'
      ? `- ${mdCode(decision.id)} — ${decision.status}: ${decision.decision} — ${decision.summary}`
      : `- ${mdCode(decision.id)} — ${decision.status}: ${decision.summary}`), '',
    '## Prohibited scope', '',
    ...index.program.prohibitedScope.map((item) => `- ${item}`), '',
    '## Freshness', '',
    `Semantic watched roots: ${index.baseline.watchedRoots.map(mdCode).join(', ')}.`,
    'Run `npm run check:project-state`. If a descendant of the audited baseline changes a watched root, Project State is stale and must be re-audited; the checker never guesses replacement semantic verdicts.', '',
    `Cold Restart Acceptance: ${mdCode(index.coldRestartAcceptance)}`, ''
  ];
  return lines.join('\n');
}

function cli() {
  const check = process.argv.slice(2).includes('--check');
  if (process.argv.slice(2).some((arg) => arg !== '--check')) {
    console.error('Usage: node scripts/checks/generate-project-state.mjs [--check]');
    process.exitCode = 2;
    return;
  }
  const rendered = renderProjectState(loadProjectState());
  if (check) {
    const current = readFileSync(generatedPath, 'utf8');
    if (current !== rendered) {
      console.error(`${relative(repositoryRoot, generatedPath)} is stale. Run node scripts/checks/generate-project-state.mjs`);
      process.exitCode = 1;
      return;
    }
    console.log('project-state generated view: PASS');
    return;
  }
  writeFileSync(generatedPath, rendered, 'utf8');
  console.log(`wrote ${relative(repositoryRoot, generatedPath)}`);
}
const isCli = process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (isCli) cli();
